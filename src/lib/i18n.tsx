const DICTS: Record<Lang, Record<Key, string>> = { en, th };

function fill(template: string, lang: Lang, params?: Msg["params"]) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = params[k];
    if (v === undefined) return "";
    return typeof v === "object" ? translate(lang, v.key as Key, v.params) : String(v);
  });
}

/** Translate a key (pure: usable outside React, e.g. in the 3D scene and the task runner). */
export function translate(lang: Lang, key: Key, params?: Msg["params"]): string {
  const template = DICTS[lang][key] ?? en[key] ?? key;
  return fill(template, lang, params);
}

/** Render a stored message, falling back to its English text for data saved before translations existed. */
export function renderMsg(lang: Lang, msg: Msg | undefined, fallback: string) {
  return msg && msg.key in en ? translate(lang, msg.key as Key, msg.params) : fallback;
}

/** Translate a short generated phrase (spot bubbles, places, roles). */
export function phrase(lang: Lang, text: string) {
  return lang === "th" ? (PHRASES_TH[text] ?? text) : text;
}

export function agentInstructions(lang: Lang, id: string, text: string) {
  return lang === "th" ? (AGENT_INSTRUCTIONS_TH[id] ?? text) : text;
}

// ---------- React binding ----------

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, params?: Msg["params"]) => string;
};

const I18n = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k, p) => translate("en", k, p) });

const LANG_KEY = "office.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY) as Lang | null;
      const initial = saved ?? (navigator.language.toLowerCase().startsWith("th") ? "th" : "en");
      // eslint-disable-next-line react-hooks/set-state-in-effect
      if (initial !== "en") setLangState(initial);
    } catch {
      // storage unavailable: stay in English
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      // storage unavailable
    }
  }, []);

  const value = useMemo<Ctx>(() => ({ lang, setLang, t: (key, params) => translate(lang, key, params) }), [lang, setLang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n() {
  return useContext(I18n);
}
